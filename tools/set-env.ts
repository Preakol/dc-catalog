/*
 * Generates src/environments/environment.ts before start, build and test.
 * Angular has no runtime process.env, so settings are baked into the bundle.
 * Values come from the process environment (CI), then .env, then defaults.
 * Everything here ends up in public JavaScript: never put secrets in it.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ENV_FILE = join(ROOT, '.env');
const OUT_FILE = join(ROOT, 'src', 'environments', 'environment.ts');

const DEFAULTS = {
  DATA_SOURCE: 'api',
  API_URL: 'http://localhost:3000',
  HEROES_API_URL: 'https://akabab.github.io/superhero-api/api',
  STRIPE_PUBLISHABLE_KEY: '',
};

type Key = keyof typeof DEFAULTS;

const KEYS = Object.keys(DEFAULTS).filter((key): key is Key => key in DEFAULTS);

const DATA_SOURCES = ['api', 'browser'];

function parseEnvFile(path: string): Map<string, string> {
  const values = new Map<string, string>();

  if (!existsSync(path)) {
    return values;
  }

  for (const raw of readFileSync(path, 'utf8').split('\n')) {
    const line = raw.trim();
    const eq = line.indexOf('=');

    if (line === '' || line.startsWith('#') || eq === -1) {
      continue;
    }

    values.set(
      line.slice(0, eq).trim(),
      line
        .slice(eq + 1)
        .trim()
        .replace(/^["']|["']$/g, ''),
    );
  }

  return values;
}

function resolve(fromFile: Map<string, string>): Record<Key, string> {
  const vars = { ...DEFAULTS };

  for (const key of KEYS) {
    const fromProcess = process.env[key];
    const fromDotEnv = fromFile.get(key);

    // A variable set in the process wins even when empty, so CI can switch features off.
    if (fromProcess !== undefined) {
      vars[key] = fromProcess;
    } else if (fromDotEnv !== undefined && fromDotEnv !== '') {
      vars[key] = fromDotEnv;
    }
  }

  return vars;
}

function render(vars: Record<Key, string>): string {
  return `// GENERATED by tools/set-env.ts from the environment and .env. Do not edit.
import type { Environment } from './environment.model';

export const environment: Environment = {
  dataSource: ${JSON.stringify(vars.DATA_SOURCE)},
  apiUrl: ${JSON.stringify(vars.API_URL)},
  heroesApiUrl: ${JSON.stringify(vars.HEROES_API_URL)},
  stripePublishableKey: ${JSON.stringify(vars.STRIPE_PUBLISHABLE_KEY)},
};
`;
}

function main(): void {
  const vars = resolve(parseEnvFile(ENV_FILE));

  if (!DATA_SOURCES.includes(vars.DATA_SOURCE)) {
    console.error(`set-env: DATA_SOURCE must be one of ${DATA_SOURCES.join(', ')}.`);
    process.exit(1);
  }

  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, render(vars));

  if (vars.STRIPE_PUBLISHABLE_KEY === '') {
    console.log('set-env: STRIPE_PUBLISHABLE_KEY is empty, checkout is disabled.');
  } else if (!vars.STRIPE_PUBLISHABLE_KEY.startsWith('pk_test_')) {
    console.log('set-env: STRIPE_PUBLISHABLE_KEY does not look like a test key (pk_test_...).');
  }

  console.log(`set-env: dataSource = ${vars.DATA_SOURCE}`);

  if (vars.DATA_SOURCE === 'api') {
    console.log(`set-env: apiUrl     = ${vars.API_URL}`);
  }
}

main();
